package com.overex.backend.event.integration;

import static org.hamcrest.Matchers.contains;
import static org.hamcrest.Matchers.hasSize;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import java.nio.file.Path;
import java.util.List;
import java.util.UUID;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.data.domain.Pageable;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;
import org.springframework.test.web.servlet.MockMvc;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.overex.backend.auth.dto.requests.SignUpAccountRequestDto;
import com.overex.backend.auth.utils.AuthTestClient;
import com.overex.backend.auth.utils.AuthTestDataFactory;
import com.overex.backend.auth.utils.TestRsaKeys;
import com.overex.backend.event.CategoryRepository;
import com.overex.backend.event.Event;
import com.overex.backend.event.EventRepository;
import com.overex.backend.event.dto.responses.CountsOfEventsDto;
import com.overex.backend.event.utils.EventTestDataFactory;
import com.overex.backend.event.utils.EventTestDataFactory.MyEventsFilterCase;
import com.overex.backend.user.User;
import com.overex.backend.user.UserRepository;

/**
 * Integration tests for "My events" ({@code GET /me/events} and
 * {@code GET /me/events/counts}): the whole application runs against the
 * in-memory H2 database of the "test" profile. Nothing is mocked.
 *
 * <p>
 * Every test signs up a real user through {@link AuthTestClient} and sends its
 * access token. The events of a tab are stored directly through the
 * repository: a finished event (start in the past) can't be created through
 * the API, because create and update both reject a start in the past.
 *
 * <p>
 * Which event lands in which tab is defined by
 * {@link EventTestDataFactory#createMyEventList()}: one DRAFT, one upcoming
 * PUBLISHED, one CANCELED and one finished event.
 */
@SpringBootTest
@AutoConfigureMockMvc
@ActiveProfiles("test")
public class MyEventsIntegrationTest {

        /** Temporary folder for the generated key files, see {@code EventIntegrationTest}. */
        @TempDir
        static Path keyDir;

        @DynamicPropertySource
        static void keyLocations(DynamicPropertyRegistry registry) {
                TestRsaKeys.writePemFiles(keyDir);
                registry.add("jwt.private-key-location", () -> keyDir.resolve("private.pem").toUri().toString());
                registry.add("jwt.public-key-location", () -> keyDir.resolve("public.pem").toUri().toString());
        }

        @Autowired
        private MockMvc mockMvc;

        @Autowired
        private ObjectMapper objectMapper;

        @Autowired
        private EventRepository eventRepository;

        @Autowired
        private UserRepository userRepository;

        @Autowired
        private CategoryRepository categoryRepository;

        /** Id of the stored festival category, generated by the database. */
        private UUID categoryDefaultId;

        /** Id of the stored concert category, generated by the database. */
        private UUID categoryConcertId;

        /** Empties the database before every test and stores the two categories. */
        @BeforeEach
        void setUpDatabase() {
                eventRepository.deleteAll();
                categoryRepository.deleteAll();
                userRepository.deleteAll();

                categoryDefaultId = categoryRepository.save(EventTestDataFactory
                                .createUnsavedCategory(EventTestDataFactory.DEFAULT_CATEGORY_TITLE)).getId();
                categoryConcertId = categoryRepository.save(EventTestDataFactory
                                .createUnsavedCategory(EventTestDataFactory.CONCERT_CATEGORY_TITLE)).getId();
        }

        /** Every tab shows exactly the events that belong to it, sorted by start. */
        @Test
        void shouldGetMyEventsForEveryTab() throws Exception {
                // Arrange (shared by every tab)
                String accessTk = AuthTestClient.signUpAndReturnAccessTk(mockMvc, objectMapper);
                storeMyEventList(findUser(AuthTestDataFactory.createSignUpDto()));
                Pageable pageable = EventTestDataFactory.createDefaultPageable();

                for (MyEventsFilterCase tab : EventTestDataFactory.createMyEventsFilterCases()) {
                        // Arrange
                        List<String> expectedTitles = EventTestDataFactory.createMyEventPage(tab.filter(), pageable)
                                        .getContent().stream().map(Event::getTitle).toList();

                        // Act + Assert
                        mockMvc.perform(get("/me/events")
                                        .param("filter", tab.filter().name())
                                        .header("Authorization", "Bearer " + accessTk))
                                        .andExpect(status().isOk())
                                        .andExpect(jsonPath("$.content", hasSize((int) tab.expectedCount())))
                                        .andExpect(jsonPath("$.content[*].title").value(contains(expectedTitles.toArray())))
                                        .andExpect(jsonPath("$.page.totalElements").value(tab.expectedCount()));
                }
        }

        /** The list only holds events the signed-in user created, never others'. */
        @Test
        void shouldGetOnlyOwnEvents() throws Exception {
                // Arrange
                String ownerAccessTk = AuthTestClient.signUpAndReturnAccessTk(mockMvc, objectMapper);
                storeMyEventList(findUser(AuthTestDataFactory.createSignUpDto()));

                SignUpAccountRequestDto otherSignUpDto = createOtherSignUpDto();
                String otherAccessTk = AuthTestClient
                                .accessTkOf(AuthTestClient.signUp(mockMvc, objectMapper, otherSignUpDto));

                // Act + Assert: the owner sees the four events
                mockMvc.perform(get("/me/events").header("Authorization", "Bearer " + ownerAccessTk))
                                .andExpect(status().isOk())
                                .andExpect(jsonPath("$.page.totalElements").value(4));

                // Act + Assert: the other user has created nothing, so the list is empty
                mockMvc.perform(get("/me/events").header("Authorization", "Bearer " + otherAccessTk))
                                .andExpect(status().isOk())
                                .andExpect(jsonPath("$.content", hasSize(0)))
                                .andExpect(jsonPath("$.page.totalElements").value(0));
        }

        /** ?categoryId narrows the tab down to that category. */
        @Test
        void shouldGetMyEventsWithCategory() throws Exception {
                // Arrange
                String accessTk = AuthTestClient.signUpAndReturnAccessTk(mockMvc, objectMapper);
                storeMyEventList(findUser(AuthTestDataFactory.createSignUpDto()));

                // Act + Assert: the concert category holds the finished event (2020) and
                // Jazz Night (2099), sorted by start
                mockMvc.perform(get("/me/events")
                                .param("categoryId", categoryConcertId.toString())
                                .header("Authorization", "Bearer " + accessTk))
                                .andExpect(status().isOk())
                                .andExpect(jsonPath("$.content[*].title").value(contains(
                                                EventTestDataFactory.FINISHED_TITLE, EventTestDataFactory.SECOND_TITLE)))
                                .andExpect(jsonPath("$.content[*].category.id")
                                                .value(contains(categoryConcertId.toString(), categoryConcertId.toString())));
        }

        @Test
        void shouldGetCountsOfEvents() throws Exception {
                // Arrange
                String accessTk = AuthTestClient.signUpAndReturnAccessTk(mockMvc, objectMapper);
                storeMyEventList(findUser(AuthTestDataFactory.createSignUpDto()));
                CountsOfEventsDto counts = EventTestDataFactory.createCountsOfEventsDto();

                // Act + Assert
                mockMvc.perform(get("/me/events/counts").header("Authorization", "Bearer " + accessTk))
                                .andExpect(status().isOk())
                                .andExpect(jsonPath("$.countOfAllEvents").value(counts.countOfAllEvents()))
                                .andExpect(jsonPath("$.countOfDraftEvents").value(counts.countOfDraftEvents()))
                                .andExpect(jsonPath("$.countOfPublishedEvents").value(counts.countOfPublishedEvents()))
                                .andExpect(jsonPath("$.countOfCanceledEvents").value(counts.countOfCanceledEvents()))
                                .andExpect(jsonPath("$.countOfFinishedEvents").value(counts.countOfFinishedEvents()));
        }

        /**
         * The token is still valid, but the account was deleted meanwhile:
         * {@code ensureUserExists} answers 404 instead of an empty list.
         */
        @Test
        void shouldNotGetMyEventsWhenUserNoLongerExists() throws Exception {
                // Arrange
                String accessTk = AuthTestClient.signUpAndReturnAccessTk(mockMvc, objectMapper);
                UUID userId = findUser(AuthTestDataFactory.createSignUpDto()).getId();
                userRepository.deleteAll();

                // Act + Assert
                mockMvc.perform(get("/me/events").header("Authorization", "Bearer " + accessTk))
                                .andExpect(status().isNotFound())
                                .andExpect(jsonPath("$.status").value(404))
                                .andExpect(jsonPath("$.message").value("User " + userId + " no longer exists."))
                                .andExpect(jsonPath("$.path").value("/me/events"));

                mockMvc.perform(get("/me/events/counts").header("Authorization", "Bearer " + accessTk))
                                .andExpect(status().isNotFound());
        }

        /** Without a token both routes are rejected by the security filter chain. */
        @Test
        void shouldRejectAnonymousAccess() throws Exception {
                // Act + Assert
                mockMvc.perform(get("/me/events"))
                                .andExpect(status().isUnauthorized());

                mockMvc.perform(get("/me/events/counts"))
                                .andExpect(status().isUnauthorized());
        }

        /** The user that signed up with the given payload, as stored in the database. */
        private User findUser(SignUpAccountRequestDto signUpDto) {
                return userRepository.findByEmail(signUpDto.email()).orElseThrow();
        }

        /** A second account; email and phone differ, because both must be unique. */
        private SignUpAccountRequestDto createOtherSignUpDto() {
                return SignUpAccountRequestDto.builder()
                                .name("Erika Musterfrau")
                                .email("other@mail.com")
                                .phone("+43987654321")
                                .password("ClearPassword")
                                .build();
        }

        /**
         * Stores {@link EventTestDataFactory#createMyEventList()} for the given owner.
         * Id and version are cleared so the database generates them; the factory
         * categories are swapped for the two stored in {@link #setUpDatabase()}.
         */
        private void storeMyEventList(User owner) {
                for (Event event : EventTestDataFactory.createMyEventList()) {
                        UUID categoryId = EventTestDataFactory.CONCERT_CATEGORY_ID.equals(event.getCategory().getId())
                                        ? categoryConcertId
                                        : categoryDefaultId;

                        event.setId(null);
                        event.setVersion(null);
                        event.setCategory(categoryRepository.getReferenceById(categoryId));
                        event.setCreatedBy(owner);
                        eventRepository.save(event);
                }
        }
}
